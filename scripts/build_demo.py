from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DATA_ROOT = ROOT / "data" / "synthetic"
REPORT_ROOT = ROOT / "reports"
OUT_PATH = ROOT / "docs" / "demo-data.js"


def build_demo_payload() -> dict:
    evaluation = json.loads(
        (REPORT_ROOT / "evaluation.json").read_text(encoding="utf-8")
    )
    trials = []

    for trial_dir in sorted(path for path in DATA_ROOT.iterdir() if path.is_dir()):
        trial_id = trial_dir.name
        meta = json.loads(
            (trial_dir / "meta.json").read_text(encoding="utf-8")
        )
        rules = json.loads(
            (trial_dir / "rules.json").read_text(encoding="utf-8")
        )
        anomalies = json.loads(
            (REPORT_ROOT / f"{trial_id}_anomalies.json").read_text(
                encoding="utf-8"
            )
        )
        result = evaluation["trials"][trial_id]
        metrics = result["metrics"]

        trials.append(
            {
                "id": trial_id,
                "title": meta["title"],
                "indication": meta["indication"],
                "phase": meta["phase"],
                "subjects": meta["subjects"],
                "rulesCount": meta["rules"],
                "injected": meta["injected_anomalies"],
                "cleanAnomalies": result["clean_anomalies"],
                "executionMs": round(
                    sum(result["timings"].values()) * 1000, 1
                ),
                "metrics": {
                    "precision": metrics["precision"],
                    "recall": metrics["recall"],
                    "f1": metrics["f1"],
                    "tp": metrics["tp"],
                    "fp": metrics["fp"],
                    "fn": metrics["fn"],
                },
                "rules": [
                    {
                        "rule_id": rule["rule_id"],
                        "code": rule["code"],
                        "domain": rule["domain"],
                        "field": rule["field"],
                        "check_type": rule["check_type"],
                        "severity": rule["severity"],
                        "section_id": rule["section_id"],
                        "section_title": rule["section_title"],
                        "quote": rule["quote"],
                    }
                    for rule in rules
                ],
                "anomalies": anomalies["injected"],
            }
        )

    payload = {
        "generatedAt": evaluation["generated_at"],
        "overall": evaluation["overall"],
        "trials": trials,
    }
    return payload


def main() -> None:
    payload = build_demo_payload()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(
        "// Generated by scripts/build_demo.py from reports/*.json\n"
        "window.CLIN_AUDIT_DATA = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(
        f"wrote {OUT_PATH} "
        f"({len(payload['trials'])} trials, "
        f"{sum(len(trial['anomalies']) for trial in payload['trials'])} anomalies)"
    )


if __name__ == "__main__":
    main()
